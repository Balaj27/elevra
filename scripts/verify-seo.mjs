import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {load} from 'cheerio';
import {absoluteUrl,shareImage,sitemapPaths,seoPages,siteUrl} from '../lib/seo.mjs';
import {firm} from '../lib/firm-content.js';
const base=process.env.PREVIEW_URL||'http://localhost:3017';
const results=[];
for(const path of sitemapPaths){
 const response=await fetch(base+path,{headers:{'User-Agent':'WhatsApp/2.24.1'}});
 assert.equal(response.status,200,path);
 const html=await response.text();
 const $=load(html);
 const head=$('head');
 const meta=name=>head.find(`meta[property="${name}"],meta[name="${name}"]`).attr('content');
 assert.equal(new URL(head.find('link[rel="canonical"]').attr('href')).href,absoluteUrl(path));
 assert.equal(new URL(meta('og:url')).href,absoluteUrl(path));
 assert.equal(meta('og:site_name'),firm.name);
 assert.equal(meta('og:image'),shareImage.url);
 assert.equal(meta('og:image:width'),'1200');
 assert.equal(meta('og:image:height'),'630');
 assert.equal(meta('og:image:type'),'image/jpeg');
 assert(meta('og:image:alt')?.includes(firm.name));
 assert.equal(meta('twitter:card'),'summary_large_image');
 assert.equal(meta('twitter:image'),shareImage.url);
 assert(meta('robots')?.includes('index, follow'));
 assert(!/noindex|nofollow/.test(meta('robots')));
 assert(!/localhost|framer/.test(head.find('link[rel="canonical"]').attr('href')));
 assert(head.find('title').text().includes(firm.name));
 if(seoPages[path])assert.equal(meta('description'),seoPages[path].description);
 const structured=$('script[type="application/ld+json"]').map((_,element)=>JSON.parse($(element).text())).get();
 const nodes=structured.flatMap(item=>item['@graph']||[item]);
 const business=nodes.find(item=>item['@type']==='AccountingService');
 assert.equal(business.name,firm.name);
 assert.equal(business.address.postalCode,'77478');
 assert.equal(business.openingHoursSpecification[0].opens,'09:00');
 assert.equal(business.hasOfferCatalog.itemListElement.length,4);
 assert(!business.telephone&&!business.email&&!business.aggregateRating);
 const breadcrumb=nodes.find(item=>item['@type']==='BreadcrumbList');
 assert.equal(breadcrumb.itemListElement.at(-1).item,absoluteUrl(path));
 if(path.startsWith('/insights/'))assert(nodes.some(item=>item['@type']==='Article'));
 results.push({path,title:head.find('title').text(),description:meta('description'),canonical:meta('og:url'),image:meta('og:image'),structuredData:true});
 console.log(path+' SEO passed');
}
const robots=await(await fetch(base+'/robots.txt')).text();
assert(robots.includes('Allow: /')&&robots.includes(absoluteUrl('/sitemap.xml')));
const sitemap=await(await fetch(base+'/sitemap.xml')).text();
for(const path of sitemapPaths)assert(sitemap.includes(absoluteUrl(path)));
assert(!sitemap.includes('<loc>'+absoluteUrl('/industries')+'</loc>'),'Redirect URL should not be in sitemap');
const image=await fetch(base+'/og/s-mago-cpa-share-v1.jpg');
assert.equal(image.status,200);assert(image.headers.get('content-type').includes('image/jpeg'));
const jpeg=Buffer.from(await image.arrayBuffer());assert(jpeg.length<1024*1024);assert.equal(jpeg.readUInt16BE(0),0xffd8);
const png=await fs.readFile('public/og/s-mago-cpa-share-v1.png');assert.equal(png.readUInt32BE(16),1200);assert.equal(png.readUInt32BE(20),630);
await fs.mkdir('verification/seo',{recursive:true});
await fs.writeFile('verification/seo/results.json',JSON.stringify({siteUrl,pages:results,robots:true,sitemap:true,image:{width:1200,height:630,bytes:jpeg.length,type:'image/jpeg'}},null,2));
console.log('All 9 routes, crawler tags, structured data, robots, sitemap, and share-image checks passed.');
